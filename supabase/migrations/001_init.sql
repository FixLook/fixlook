create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text not null,
  email text not null unique,
  phone text,
  role public.user_role not null default 'customer',
  city text,
  created_at timestamptz not null default now()
);

create table if not exists public.services (
  id integer generated by default as identity primary key,
  name text not null unique,
  description text,
  base_price integer not null check (base_price >= 0),
  active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.masters (
  id integer generated by default as identity primary key,
  profile_id uuid not null unique references public.profiles(id) on delete cascade,
  description text,
  hourly_rate integer check (hourly_rate is null or hourly_rate >= 0),
  verified boolean not null default false,
  available boolean not null default false,
  rating_avg numeric(3, 2) not null default 0,
  created_at timestamptz not null default now()
);

create table if not exists public.orders (
  id uuid primary key default gen_random_uuid(),
  order_number text not null unique,
  customer_id uuid not null references public.profiles(id) on delete cascade,
  master_id uuid references public.profiles(id) on delete set null,
  service_id integer not null references public.services(id),
  problem_description text not null,
  address text not null,
  city text not null default 'Kosice',
  preferred_datetime timestamptz,
  status public.order_status not null default 'new',
  estimated_price integer,
  final_price integer,
  commission_amount integer,
  stripe_payment_status text,
  created_at timestamptz not null default now(),
  completed_at timestamptz
);

create table if not exists public.order_photos (
  id uuid primary key default gen_random_uuid(),
  order_id uuid not null references public.orders(id) on delete cascade,
  photo_url text not null,
  created_at timestamptz not null default now()
);

create table if not exists public.ratings (
  id uuid primary key default gen_random_uuid(),
  order_id uuid not null unique references public.orders(id) on delete cascade,
  customer_id uuid not null references public.profiles(id) on delete cascade,
  master_id uuid not null references public.profiles(id) on delete cascade,
  stars integer not null check (stars between 1 and 5),
  comment text,
  created_at timestamptz not null default now()
);

create table if not exists public.payments (
  id uuid primary key default gen_random_uuid(),
  order_id uuid not null unique references public.orders(id) on delete cascade,
  stripe_payment_intent_id text,
  amount integer not null check (amount >= 0),
  commission_amount integer not null check (commission_amount >= 0),
  master_amount integer not null check (master_amount >= 0),
  status public.payment_status not null default 'pending',
  created_at timestamptz not null default now()
);

